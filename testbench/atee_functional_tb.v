`timescale 1ns / 1ps
//////////////////////////////////////////////////////////////////////////////////
// Module: atee_functional_tb
//
// FUNCTIONAL VERIFICATION TESTBENCH for Coreless-V
// Matches the I2SRV32-V repo's benchmark methodology exactly.
//
// TEST 1 (conv8_3): 8x8 ramp image, 3x3x16 integer kernels, no bias, no ReLU
//   - Same data as benchmarks/benchmarks/conv/conv8_3/
//   - Expected output: 576 values (6x6x16) verified against repo's expected_output.c
//   - Error tolerance: ±10 (same as repo's err_limit)
//
// TEST 2 (mnist_conv1): 28x28 MNIST digit "7", trained kernels, with bias + ReLU
//   - Same data as benchmarks/benchmarks/cnn_demo/ Conv1 layer
//   - Expected output: 10816 values (26x26x16) from Python golden reference
//
// METRICS MEASURED (matching repo's paper):
//   1. Cycle count      — from Coreless-V cycle_count register
//   2. Execution time   — cycles / 50 MHz
//   3. Functional error — count of |computed - expected| > err_limit
//   4. Error rate       — err_count / total_outputs
//
// Data loaded via $readmemh from .hex files generated by generate_test_data.py
//////////////////////////////////////////////////////////////////////////////////

module atee_functional_tb;

    // =========================================================================
    // Parameters — match repo metrics
    // =========================================================================
    parameter CLK_PERIOD   = 20;       // 50 MHz (same as repo FPGA clock)
    parameter ERR_LIMIT    = 10;       // Same as repo's err_limit in conv benchmarks

    // Test 1 dimensions (conv8_3)
    parameter T1_IMG_SIZE  = 8;
    parameter T1_KER_SIZE  = 3;
    parameter T1_N_FILT    = 16;
    parameter T1_OUT_SIZE  = 6;        // 8 - 3 + 1
    parameter T1_OUT_TOTAL = 576;      // 6 * 6 * 16
    parameter T1_IMG_WORDS = 64;       // 8 * 8
    parameter T1_KER_WORDS = 144;      // 3 * 3 * 16

    // Test 2 dimensions (mnist_conv1)
    parameter T2_IMG_SIZE  = 28;
    parameter T2_KER_SIZE  = 3;
    parameter T2_N_FILT    = 16;
    parameter T2_OUT_SIZE  = 26;       // 28 - 3 + 1
    parameter T2_OUT_TOTAL = 10816;    // 26 * 26 * 16
    parameter T2_IMG_WORDS = 784;      // 28 * 28
    parameter T2_KER_WORDS = 144;      // 3 * 3 * 16

    // =========================================================================
    // Clock and reset
    // =========================================================================
    reg clk, reset;
    initial clk = 0;
    always #(CLK_PERIOD/2) clk = ~clk;

    // =========================================================================
    // DUT signals
    // =========================================================================
    reg  [8:0]  vl;
    reg  [1:0]  vcsr_quant;
    reg         I_clear;
    reg  [2:0]  I_id;
    wire        ALU_mon;
    wire        stall_out;
    wire        DONE_out;

    reg  [31:0] proc_addr;
    reg  [31:0] proc_din;
    wire [31:0] proc_dout;
    reg         proc_we;

    wire [4:0]  XRF_ADDR;
    wire [31:0] XRF_DATAWR;
    wire        XRF_WE;

    reg         I_start;
    reg  [4:0]  I_vs1, I_vs2, I_vd;
    reg  [31:0] I_RS1, I_RS2;
    reg  [4:0]  I_uimm5;
    reg  [7:0]  I_funct;
    reg  [1:0]  I_permute;
    reg         I_mask_en;
    reg  [1:0]  I_ALUSrc;
    reg         I_dmr, I_dmw;
    reg         I_reg_we, I_mem_reg;
    reg         I_Xout;
    reg  [1:0]  I_mode_lsu;

    // DMA Wishbone
    wire [31:0] wb_dma_adr_o;
    wire [31:0] wb_dma_dat_o;
    reg  [31:0] wb_dma_dat_i;
    wire        wb_dma_we_o;
    wire [3:0]  wb_dma_sel_o;
    wire        wb_dma_stb_o;
    wire        wb_dma_cyc_o;
    reg         wb_dma_ack_i;

    // =========================================================================
    // DUT
    // =========================================================================
    atee_top dut (
        .clk          (clk),
        .reset        (reset),
        .vl           (vl),
        .vcsr_quant   (vcsr_quant),
        .I_clear      (I_clear),
        .I_id         (I_id),
        .ALU_mon      (ALU_mon),
        .stall        (stall_out),
        .DONE         (DONE_out),
        .proc_addr    (proc_addr),
        .proc_din     (proc_din),
        .proc_dout    (proc_dout),
        .proc_we      (proc_we),
        .XRF_ADDR     (XRF_ADDR),
        .XRF_DATAWR   (XRF_DATAWR),
        .XRF_WE       (XRF_WE),
        .I_start      (I_start),
        .I_vs1        (I_vs1),
        .I_vs2        (I_vs2),
        .I_vd         (I_vd),
        .I_RS1        (I_RS1),
        .I_RS2        (I_RS2),
        .I_uimm5      (I_uimm5),
        .I_funct      (I_funct),
        .I_permute    (I_permute),
        .I_mask_en    (I_mask_en),
        .I_ALUSrc     (I_ALUSrc),
        .I_dmr        (I_dmr),
        .I_dmw        (I_dmw),
        .I_reg_we     (I_reg_we),
        .I_mem_reg    (I_mem_reg),
        .I_Xout       (I_Xout),
        .I_mode_lsu   (I_mode_lsu),
        .wb_dma_adr_o (wb_dma_adr_o),
        .wb_dma_dat_o (wb_dma_dat_o),
        .wb_dma_dat_i (wb_dma_dat_i),
        .wb_dma_we_o  (wb_dma_we_o),
        .wb_dma_sel_o (wb_dma_sel_o),
        .wb_dma_stb_o (wb_dma_stb_o),
        .wb_dma_cyc_o (wb_dma_cyc_o),
        .wb_dma_ack_i (wb_dma_ack_i)
    );

    // =========================================================================
    // Simulated DRAM — 128K words, loaded from hex files
    // =========================================================================
    reg [31:0] dram_mem [0:131071];  // 512 KB

    // Wishbone slave: 1-cycle acknowledge (models ideal DRAM)
    always @(posedge clk) begin
        if (reset) begin
            wb_dma_ack_i <= 1'b0;
            wb_dma_dat_i <= 32'd0;
        end else if (wb_dma_stb_o && wb_dma_cyc_o && !wb_dma_ack_i) begin
            wb_dma_dat_i <= dram_mem[wb_dma_adr_o[18:2]];
            wb_dma_ack_i <= 1'b1;
        end else begin
            wb_dma_ack_i <= 1'b0;
        end
    end

    // =========================================================================
    // Golden reference storage
    // =========================================================================
    reg [31:0] golden_t1 [0:T1_OUT_TOTAL-1];   // 576 values
    reg [31:0] golden_t2 [0:T2_OUT_TOTAL-1];   // 10816 values

    // =========================================================================
    // Config register addresses
    // =========================================================================
    localparam CFG_BASE       = 32'h0020_0000;
    localparam CFG_INPUT_H    = CFG_BASE + 32'h00;
    localparam CFG_INPUT_W    = CFG_BASE + 32'h04;
    localparam CFG_INPUT_C    = CFG_BASE + 32'h08;
    localparam CFG_KERNEL_H   = CFG_BASE + 32'h0C;
    localparam CFG_KERNEL_W   = CFG_BASE + 32'h10;
    localparam CFG_OUTPUT_C   = CFG_BASE + 32'h14;
    localparam CFG_STRIDE     = CFG_BASE + 32'h18;
    localparam CFG_PADDING    = CFG_BASE + 32'h1C;
    localparam CFG_POOL_SIZE  = CFG_BASE + 32'h20;
    localparam CFG_Q_FORMAT   = CFG_BASE + 32'h24;
    localparam CFG_ACTIVATION = CFG_BASE + 32'h28;
    localparam CFG_INPUT_BASE = CFG_BASE + 32'h2C;
    localparam CFG_WEIGHT_BASE= CFG_BASE + 32'h30;
    localparam CFG_OUTPUT_BASE= CFG_BASE + 32'h34;
    localparam CFG_LAYER_START= CFG_BASE + 32'h38;
    localparam CFG_STATUS     = CFG_BASE + 32'h3C;
    localparam CFG_CYCLE_CNT  = CFG_BASE + 32'h40;
    localparam CFG_DMA_SRC    = CFG_BASE + 32'h44;
    localparam CFG_DMA_DST    = CFG_BASE + 32'h48;
    localparam CFG_DMA_LEN    = CFG_BASE + 32'h4C;
    localparam CFG_DMA_START  = CFG_BASE + 32'h50;
    localparam CFG_DMA_STATUS = CFG_BASE + 32'h54;

    // DMEM regions
    localparam DMEM_INPUT_BASE  = 32'h0010_0000;
    localparam DMEM_WEIGHT_BASE = 32'h0014_0000;
    localparam DMEM_OUTPUT_BASE = 32'h0016_0000;

    // DRAM layout: test1 data at offset 0, test2 data at offset 0x10000
    localparam DRAM_T1_IMG = 32'h0000_0000;
    localparam DRAM_T1_KER = 32'h0000_0400;  // offset 256 words (1024 bytes)
    localparam DRAM_T2_IMG = 32'h0001_0000;   // offset 16K words
    localparam DRAM_T2_KER = 32'h0001_2000;   // offset 16K + 2K words

    // =========================================================================
    // Helper tasks
    // =========================================================================
    task write_cfg(input [31:0] addr, input [31:0] data);
    begin
        @(posedge clk);
        proc_addr <= addr;
        proc_din  <= data;
        proc_we   <= 1'b1;
        @(posedge clk);
        proc_we   <= 1'b0;
    end
    endtask

    task read_cfg(input [31:0] addr, output [31:0] data);
    begin
        @(posedge clk);
        proc_addr <= addr;
        proc_we   <= 1'b0;
        @(posedge clk);
        @(posedge clk);  // Extra cycle for readback latency
        data = proc_dout;
    end
    endtask

    task dma_transfer(input [31:0] src, input [31:0] dst, input [31:0] len);
        reg [31:0] stat;
    begin
        write_cfg(CFG_DMA_SRC, src);
        write_cfg(CFG_DMA_DST, dst);
        write_cfg(CFG_DMA_LEN, len);
        write_cfg(CFG_DMA_START, 32'd1);
        stat = 32'h0000_0001;
        while (stat[0]) begin
            read_cfg(CFG_DMA_STATUS, stat);
            #(CLK_PERIOD * 10);
        end
    end
    endtask

    task run_layer;
        reg [31:0] stat;
    begin
        write_cfg(CFG_LAYER_START, 32'd1);
        stat = 32'h0000_0001;
        while (stat[0]) begin
            read_cfg(CFG_STATUS, stat);
            #(CLK_PERIOD * 100);
        end
    end
    endtask

    // =========================================================================
    // Metrics counters
    // =========================================================================
    integer err_count;
    integer total_checked;
    reg [31:0] cycle_count;
    integer i;
    reg [31:0] computed_val;
    reg [31:0] expected_val;
    reg signed [31:0] diff;
    reg [31:0] status_val;

    // Track max absolute error
    integer max_abs_err;
    integer abs_err;

    // For performance comparison logging
    real exec_time_us;

    // =========================================================================
    // Load test data from hex files
    // =========================================================================
    initial begin
        // Initialize DRAM to zero
        for (i = 0; i < 131072; i = i + 1)
            dram_mem[i] = 32'd0;

        // Load Test 1 data into DRAM
        //   Input image at DRAM offset 0 (64 words)
        $readmemh("test1_input.hex",   dram_mem, 0, T1_IMG_WORDS - 1);
        //   Weights at DRAM offset 256 (144 words)
        $readmemh("test1_weights.hex", dram_mem, 256, 256 + T1_KER_WORDS - 1);

        // Load golden reference
        $readmemh("test1_golden.hex",  golden_t1, 0, T1_OUT_TOTAL - 1);

        $display("Data files loaded successfully.");
        $display("  Test 1 image: %0d words from test1_input.hex", T1_IMG_WORDS);
        $display("  Test 1 weights: %0d words from test1_weights.hex", T1_KER_WORDS);
        $display("  Test 1 golden: %0d words from test1_golden.hex", T1_OUT_TOTAL);
    end

    // =========================================================================
    // Main test sequence
    // =========================================================================
    initial begin
        // Initialize all signals
        vl          = 9'd8;
        vcsr_quant  = 2'b00;     // Q32.0 (plain integer, matching conv8_3)
        I_clear     = 1'b0;
        I_id        = 3'd0;
        proc_addr   = 32'd0;
        proc_din    = 32'd0;
        proc_we     = 1'b0;
        I_start     = 1'b0;
        I_vs1       = 5'd0;  I_vs2  = 5'd0;  I_vd   = 5'd0;
        I_RS1       = 32'd0; I_RS2  = 32'd0;
        I_uimm5     = 5'd0;
        I_funct     = 8'd0;
        I_permute   = 2'd0;
        I_mask_en   = 1'b0;
        I_ALUSrc    = 2'b00;
        I_dmr       = 1'b0;  I_dmw  = 1'b0;
        I_reg_we    = 1'b0;  I_mem_reg = 1'b0;
        I_Xout      = 1'b0;
        I_mode_lsu  = 2'b00;

        // Reset
        reset = 1'b1;
        #(CLK_PERIOD * 20);
        reset = 1'b0;
        #(CLK_PERIOD * 5);

        $display("");
        $display("################################################################");
        $display("# Coreless-V Functional Verification Testbench");
        $display("# Benchmark methodology: I2SRV32-V repo (conv8_3 + mnist_conv1)");
        $display("# Clock: 50 MHz, Error tolerance: +/-%0d", ERR_LIMIT);
        $display("################################################################");

        // =================================================================
        // TEST 1: conv8_3 — matches repo's benchmarks/conv/conv8_3
        // =================================================================
        $display("");
        $display("================================================================");
        $display("  TEST 1: conv8_3 (8x8 ramp, 3x3x16 integer kernels)");
        $display("  Reference: I2SRV32-V benchmarks/benchmarks/conv/conv8_3/");
        $display("================================================================");

        // Step 1: Configure layer dimensions
        $display("  [1/5] Writing layer configuration...");
        write_cfg(CFG_INPUT_H,    T1_IMG_SIZE);
        write_cfg(CFG_INPUT_W,    T1_IMG_SIZE);
        write_cfg(CFG_INPUT_C,    32'd1);
        write_cfg(CFG_KERNEL_H,   T1_KER_SIZE);
        write_cfg(CFG_KERNEL_W,   T1_KER_SIZE);
        write_cfg(CFG_OUTPUT_C,   T1_N_FILT);
        write_cfg(CFG_STRIDE,     32'd1);
        write_cfg(CFG_PADDING,    32'd0);
        write_cfg(CFG_POOL_SIZE,  32'd0);          // No pooling
        write_cfg(CFG_Q_FORMAT,   32'd0);           // Q32.0 (plain integer)
        write_cfg(CFG_ACTIVATION, 32'd0);           // No ReLU (conv8_3 has none)

        // Step 2: DMA input image (64 words)
        $display("  [2/5] DMA: loading input image (%0d words)...", T1_IMG_WORDS);
        write_cfg(CFG_INPUT_BASE,  DMEM_INPUT_BASE);
        write_cfg(CFG_WEIGHT_BASE, DMEM_WEIGHT_BASE);
        write_cfg(CFG_OUTPUT_BASE, DMEM_OUTPUT_BASE);
        dma_transfer(DRAM_T1_IMG, DMEM_INPUT_BASE, T1_IMG_WORDS);
        $display("         Input DMA complete.");

        // === DIAGNOSTIC: verify DMA actually wrote data to DMEM ===
        // Data stored with 32-byte spacing (bank 0 only)
        proc_addr = DMEM_INPUT_BASE;
        proc_we   = 1'b0;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[INPUT_BASE+0]  = 0x%08h (expect 0x00000000 = pixel[0][0])", proc_dout);
        proc_addr = DMEM_INPUT_BASE + 32'h20;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[INPUT_BASE+20] = 0x%08h (expect 0x00000001 = pixel[0][1])", proc_dout);
        proc_addr = DMEM_INPUT_BASE + 32'h40;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[INPUT_BASE+40] = 0x%08h (expect 0x00000002 = pixel[0][2])", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[WEIGHT_BASE+0] = 0x%08h (expect first weight)", proc_dout);

        // Step 3: DMA weights (144 words)
        $display("  [3/5] DMA: loading weights (%0d words)...", T1_KER_WORDS);
        dma_transfer(DRAM_T1_KER, DMEM_WEIGHT_BASE, T1_KER_WORDS);
        $display("         Weight DMA complete.");

        // === DIAGNOSTIC: verify weight DMA — read first 9 weights at HBM offsets ===
        // Weights stored with 32-byte spacing (bank 0 only)
        proc_we = 1'b0;
        proc_addr = DMEM_WEIGHT_BASE + 32'h00;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k0] @+0x00  = 0x%08h (expect 1)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'h20;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k1] @+0x20  = 0x%08h (expect 2)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'h40;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k2] @+0x40  = 0x%08h (expect 3)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'h60;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k3] @+0x60  = 0x%08h (expect 4)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'h80;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k4] @+0x80  = 0x%08h (expect 5)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'hA0;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k5] @+0xA0  = 0x%08h (expect 6)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'hC0;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k6] @+0xC0  = 0x%08h (expect 7)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'hE0;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k7] @+0xE0  = 0x%08h (expect 8)", proc_dout);
        proc_addr = DMEM_WEIGHT_BASE + 32'h100;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] WEIGHT[oc0,k8] @+0x100 = 0x%08h (expect 9)", proc_dout);

        // Step 4: Execute convolution
        $display("  [4/5] Executing Conv2D (%0dx%0dx1 * %0dx%0dx1x%0d)...",
                 T1_IMG_SIZE, T1_IMG_SIZE, T1_KER_SIZE, T1_KER_SIZE, T1_N_FILT);
        run_layer;

        // Read cycle count
        read_cfg(CFG_CYCLE_CNT, cycle_count);
        exec_time_us = cycle_count / 50.0;
        $display("         Conv2D complete.");

        // === DIAGNOSTIC: check first few output DMEM locations ===
        // Output stored with 32-byte spacing (bank 0 only)
        proc_addr = DMEM_OUTPUT_BASE;
        proc_we   = 1'b0;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[OUTPUT_BASE+0]  = 0x%08h (expect 0x0000022b = 555)", proc_dout);
        proc_addr = DMEM_OUTPUT_BASE + 32'h20;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[OUTPUT_BASE+20] = 0x%08h (expect 0x00000258 = 600)", proc_dout);
        proc_addr = DMEM_OUTPUT_BASE + 32'h40;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[OUTPUT_BASE+40] = 0x%08h (expect 0x00000285 = 645)", proc_dout);
        proc_addr = DMEM_OUTPUT_BASE + 32'h60;
        @(posedge clk); @(posedge clk); @(posedge clk);
        $display("  [DBG] DMEM[OUTPUT_BASE+60] = 0x%08h (expect 0x000002b2 = 690)", proc_dout);

        // Step 5: Verify output against golden reference
        $display("  [5/5] Verifying output (%0d values, tolerance +/-%0d)...",
                 T1_OUT_TOTAL, ERR_LIMIT);
        err_count    = 0;
        max_abs_err  = 0;
        total_checked = 0;

        for (i = 0; i < T1_OUT_TOTAL; i = i + 1) begin
            // Read computed output from DMEM (32-byte spacing, bank 0 only)
            proc_addr = DMEM_OUTPUT_BASE + (i * 32);
            proc_we   = 1'b0;
            @(posedge clk);
            @(posedge clk);
            computed_val = proc_dout;
            expected_val = golden_t1[i];

            // Signed difference (same as repo: Y[i] - expected_output[i])
            diff = $signed(computed_val) - $signed(expected_val);
            if (diff < 0) abs_err = -diff;
            else          abs_err = diff;

            if (abs_err > max_abs_err)
                max_abs_err = abs_err;

            // Error check (same threshold as repo)
            if (diff > ERR_LIMIT || diff < -ERR_LIMIT) begin
                err_count = err_count + 1;
                if (err_count <= 10) // Print first 10 mismatches
                    $display("    MISMATCH[%0d]: computed=0x%08h expected=0x%08h diff=%0d",
                             i, computed_val, expected_val, diff);
            end

            total_checked = total_checked + 1;
        end

        // =====================================================================
        // TEST 1 RESULTS — formatted for paper Table
        // =====================================================================
        $display("");
        $display("  ┌─────────────────────────────────────────────────────�?");
        $display("  │          TEST 1 RESULTS: conv8_3                   │");
        $display("  ├─────────────────────────────────────────────────────┤");
        $display("  │  Output elements checked : %6d / %6d         │", total_checked, T1_OUT_TOTAL);
        $display("  │  Errors (|diff| > %3d)   : %6d                   │", ERR_LIMIT, err_count);
        $display("  │  Error rate              : %0d.%02d%%                       │",
                 (err_count * 100) / T1_OUT_TOTAL,
                 ((err_count * 10000) / T1_OUT_TOTAL) % 100);
        $display("  │  Max absolute error      : %6d                   │", max_abs_err);
        $display("  │  Coreless-V Cycle count        : %6d cycles            │", cycle_count);
        $display("  │  Execution time @50MHz   : %0d.%02d us               │",
                 $rtoi(exec_time_us), $rtoi((exec_time_us * 100)) % 100);
        if (err_count == 0)
            $display("  │  STATUS                  :  ** PASS **              │");
        else
            $display("  │  STATUS                  :  ** FAIL **              │");
        $display("  └─────────────────────────────────────────────────────┘");
        $display("");

        // =====================================================================
        // Performance comparison placeholder
        // (Fill in repo's cycle count from simulation after running their design)
        // =====================================================================
        $display("  ┌─────────────────────────────────────────────────────�?");
        $display("  │     PERFORMANCE COMPARISON (for paper)             │");
        $display("  ├─────────────────────────────────────────────────────┤");
        $display("  │  Metric         │ I2SRV32-V  │ Coreless-V  │ Gain  │");
        $display("  ├─────────────────┼────────────┼────────────┼───────┤");
        $display("  │  Cycles (conv8) │ [measure]  │ %10d │  ---  │", cycle_count);
        $display("  │  Error count    │ [repo: 0]  │ %10d │  ---  │", err_count);
        $display("  │  Clock (MHz)    │     50     │     50     │  1.0x │");
        $display("  └─────────────────┴────────────┴────────────┴───────┘");
        $display("");
        $display("  NOTE: To fill in I2SRV32-V column, run the original repo's");
        $display("  conv8_3 benchmark in Vivado behavioral simulation and read");
        $display("  the cycle count from the waveform viewer.");

        // =================================================================
        // Done
        // =================================================================
        $display("");
        $display("################################################################");
        $display("#  Simulation complete at time %0t", $time);
        if (err_count == 0)
            $display("#  ALL TESTS PASSED");
        else
            $display("#  TESTS FAILED: %0d errors detected", err_count);
        $display("################################################################");

        #(CLK_PERIOD * 10);
        $finish;
    end

    // =========================================================================
    // Waveform dump
    // =========================================================================
    initial begin
        $dumpfile("atee_functional_tb.vcd");
        $dumpvars(0, atee_functional_tb);
    end

    // =========================================================================
    // Timeout watchdog (200ms at 50MHz = 10M cycles)
    // =========================================================================
    initial begin
        #(CLK_PERIOD * 10_000_000);
        $display("ERROR: Simulation timeout after 10M cycles!");
        $display("  This may indicate the FSM is stuck.");
        $display("  Check hbm_lite_controller state signal in waveform.");
        $finish;
    end

    // =========================================================================
    // VRF + Pipeline monitor — traces first output pixel (oc=0, oh=0, ow=0)
    // Prints HBM state and DONE signals when state changes during first pixel
    // =========================================================================
    reg [3:0] prev_hbm_state;
    reg [15:0] pixel_num;  // which output pixel we're on
    wire [3:0] hbm_state = dut.u_hbm_lite.state;
    wire [15:0] hbm_kw = dut.u_hbm_lite.kw_cnt;
    wire [15:0] hbm_kh = dut.u_hbm_lite.kh_cnt;
    wire [15:0] hbm_oc = dut.u_hbm_lite.oc_cnt;
    wire [15:0] hbm_oh = dut.u_hbm_lite.oh_cnt;
    wire [15:0] hbm_ow = dut.u_hbm_lite.ow_cnt;
    wire        hbm_first = dut.u_hbm_lite.first_iter;
    wire [31:0] hbm_input_addr = dut.u_hbm_lite.comb_input_addr;
    wire [31:0] hbm_weight_addr = dut.u_hbm_lite.comb_weight_addr;
    wire [31:0] hbm_output_addr = dut.u_hbm_lite.comb_output_addr;

    // v_wrapper DONE signal (available from Verilog side)
    wire        vw_done_sig = dut.u_vec_unit.DONE;

    initial begin
        prev_hbm_state = 4'd0;
        pixel_num = 0;
    end

    always @(posedge clk) begin
        if (hbm_state != prev_hbm_state) begin
            // Track pixel number
            if (prev_hbm_state == 4'd14) // S_NEXT_PIXEL
                pixel_num <= pixel_num + 1;

            // Only trace the first 2 pixels (oc=0, oh=0, ow=0..1)
            if (pixel_num < 2 && hbm_state >= 4'd3) begin
                $display("  [TRACE t=%0t] pixel=%0d HBM:%0d->%0d oc=%0d oh=%0d ow=%0d kh=%0d kw=%0d first=%b | inp_addr=0x%08h wt_addr=0x%08h out_addr=0x%08h | DONE=%b",
                    $time, pixel_num, prev_hbm_state, hbm_state,
                    hbm_oc, hbm_oh, hbm_ow, hbm_kh, hbm_kw, hbm_first,
                    hbm_input_addr, hbm_weight_addr, hbm_output_addr,
                    vw_done_sig);
            end
        end
        prev_hbm_state <= hbm_state;
    end

    // Monitor DMA writes to verify 32-byte spacing works
    wire [31:0] dma_addr  = dut.u_dma.dmem_addr;
    wire [31:0] dma_data  = dut.u_dma.dmem_din;
    wire        dma_we    = dut.u_dma.dmem_we;
    reg [15:0]  dma_wr_count;
    initial dma_wr_count = 0;

    always @(posedge clk) begin
        if (dma_we) begin
            if (dma_wr_count < 5 || (dma_wr_count >= 64 && dma_wr_count < 67))
                $display("  [DMA_WR %0d] addr=0x%08h data=0x%08h bank=%0d word=%0d",
                    dma_wr_count, dma_addr, dma_data,
                    dma_addr[4:2], dma_addr[18:5]);
            dma_wr_count <= dma_wr_count + 1;
        end
    end

    // Monitor vec_unit DONE and instruction on key transitions
    wire [4:0]  vec_vd_out = dut.u_hbm_lite.vec_vd;
    wire        vec_dmr_out = dut.u_hbm_lite.vec_dmr;
    wire        vec_dmw_out = dut.u_hbm_lite.vec_dmw;
    wire [7:0]  vec_funct_out = dut.u_hbm_lite.vec_funct;

    // Monitor mux signals going to v_wrapper to see actual instructions
    wire        mux_start_mon  = dut.mux_start;
    wire        mux_dmr_mon    = dut.mux_dmr;
    wire        mux_dmw_mon    = dut.mux_dmw;
    wire        mux_reg_we_mon = dut.mux_reg_we;
    wire        mux_mem_reg_mon= dut.mux_mem_reg;
    wire [31:0] mux_rs1_mon    = dut.mux_RS1;
    wire [4:0]  mux_vd_mon     = dut.mux_vd;
    wire [4:0]  mux_vs1_mon    = dut.mux_vs1;
    wire [4:0]  mux_vs2_mon    = dut.mux_vs2;
    wire [7:0]  mux_funct_mon  = dut.mux_funct;
    wire        vw_done_mon    = dut.vw_done;
    wire [31:0] vw_proc_dout_mon = dut.vw_proc_dout;

    // Trace first pixel's first LOAD_INPUT instruction in detail
    reg         trace_active;
    reg [3:0]   trace_cnt;
    initial begin trace_active = 0; trace_cnt = 0; end

    always @(posedge clk) begin
        // Start tracing when first LOAD_INPUT happens (state 3 for kh=0,kw=0 of pixel 0)
        if (hbm_state == 4'd3 && prev_hbm_state == 4'd2 && pixel_num == 0) begin
            trace_active <= 1;
            trace_cnt <= 0;
        end

        if (trace_active) begin
            $display("  [PIPE t=%0t] cnt=%0d HBM_st=%0d | start=%b dmr=%b dmw=%b rwe=%b mreg=%b funct=%02h vd=%0d vs1=%0d vs2=%0d RS1=0x%08h | DONE=%b",
                $time, trace_cnt, hbm_state,
                mux_start_mon, mux_dmr_mon, mux_dmw_mon, mux_reg_we_mon, mux_mem_reg_mon,
                mux_funct_mon, mux_vd_mon, mux_vs1_mon, mux_vs2_mon, mux_rs1_mon,
                vw_done_mon);
            trace_cnt <= trace_cnt + 1;
            // Trace first 30 cycles of first instruction sequence
            if (trace_cnt >= 30)
                trace_active <= 0;
        end
    end

endmodule
